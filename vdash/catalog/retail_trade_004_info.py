def apply(kpis) -> None:
    by_id = {k.id: k for k in kpis}
    missing = [k.id for k in kpis if k.id not in INFO]
    if missing:  # every chart gets business wording (enforced here and by the tests)
        raise ValueError(f"no business description for: {missing}")
    for kid, title in TITLES.items():
        by_id[kid].title = title
    for kid, text in INFO.items():
        by_id[kid].desc = text
    for kid, text in NOTES.items():
        by_id[kid].note = text
    for (kid, old), new in SERIES.items():
        for s in by_id[kid].series:
            if s.name == old:
                s.name = new


